export function parseSoundLevel(raw: string): number {
  if (!raw) return 0;
  const num = parseFloat(raw.replace(/[^0-9.]/g, ''));
  return isNaN(num) ? 0 : num;
}

export function getSoundLevelDisplay(spot: SoundSpot): string {
  const min = parseSoundLevel(spot.soundLevelMin);
  const max = parseSoundLevel(spot.soundLevelMax);
  if (min > 0 && max > 0) return `${min}–${max} dBA`;
  if (max > 0) return `${max} dBA`;
  if (min > 0) return `${min} dBA`;
  return 'N/A';
}

export function getAverageSoundLevel(spot: SoundSpot): number {
  const min = parseSoundLevel(spot.soundLevelMin);
  const max = parseSoundLevel(spot.soundLevelMax);
  if (min > 0 && max > 0) return Math.round((min + max) / 2);
  if (max > 0) return max;
  if (min > 0) return min;
  return 0;
}

export function getSoundLevelLabel(spot: SoundSpot): string {
  const avg = getAverageSoundLevel(spot);
  if (avg === 0) return 'Unknown';
  if (avg < 50) return 'Quiet';
  if (avg < 65) return 'Moderate';
  if (avg < 75) return 'Lively';
  return 'Loud';
}

